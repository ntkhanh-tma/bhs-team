#!/usr/bin/env node
/**
 * Reads config from .env.local (local dev) or process.env (CI/CD)
 * and writes src/environments/environment.ts + environment.development.ts.
 *
 * CI usage: set API_BASE_URL (the .NET API origin, e.g.
 *           https://bhs-team-api.azurewebsites.net) and API_NINJAS_KEY as
 *           environment variables (GitHub Actions secrets) before running.
 *
 * NOTE: there is no shared secret any more. The old Apps Script gateway required
 * one to be embedded in the bundle, which SECURITY.md correctly called
 * obfuscation rather than confidentiality. The .NET API authenticates each user
 * with a JWT instead, so nothing secret ships to the browser.
 */
const fs = require('fs');
const path = require('path');

function readEnvLocal() {
  const envPath = path.join(__dirname, '..', '.env.local');
  if (!fs.existsSync(envPath)) return {};
  const vars = {};
  fs.readFileSync(envPath, 'utf-8')
    .split('\n')
    .forEach(line => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) return;
      const eq = trimmed.indexOf('=');
      if (eq < 0) return;
      const key = trimmed.slice(0, eq).trim();
      const val = trimmed.slice(eq + 1).trim();
      vars[key] = val;
    });
  return vars;
}

// The API origin is a public URL, not a secret — so it has a sensible default
// rather than living in a repo secret. Override with API_BASE_URL for local dev
// (http://localhost:5199) or if the App Service is ever renamed.
const DEFAULT_API_BASE_URL =
  'https://bhs-team-fgf3cfgqhxbjctax.southeastasia-01.azurewebsites.net';

const local = readEnvLocal();
const apiBaseUrl = (local.API_BASE_URL ?? process.env.API_BASE_URL ?? DEFAULT_API_BASE_URL)
  .replace(/\/+$/, '');
const apiNinjasKey = local.API_NINJAS_KEY ?? process.env.API_NINJAS_KEY ?? '';

if (apiBaseUrl === DEFAULT_API_BASE_URL) {
  console.log(`[setup-env] Using default API base URL: ${apiBaseUrl}`);
}
if (!apiBaseUrl) {
  // Only reachable if someone explicitly sets API_BASE_URL to an empty string.
  console.error('[setup-env] ERROR: API_BASE_URL resolved to empty — the app would have no backend.');
  process.exit(1);
}
if (!apiNinjasKey) {
  console.warn('[setup-env] WARNING: API_NINJAS_KEY is empty — daily quote will not work.');
}

const envDir = path.join(__dirname, '..', 'src', 'environments');
fs.mkdirSync(envDir, { recursive: true });

const tpl = (prod) => `// Auto-generated by scripts/setup-env.js — do not edit manually.
export const environment = {
  production: ${prod},
  apiBaseUrl: '${apiBaseUrl}',
  apiNinjasKey: '${apiNinjasKey}',
};
`;

fs.writeFileSync(path.join(envDir, 'environment.ts'), tpl(true));
fs.writeFileSync(path.join(envDir, 'environment.development.ts'), tpl(false));
console.log('[setup-env] Environment files written to src/environments/');
